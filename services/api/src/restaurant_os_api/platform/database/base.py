"""Declarative base with the platform-wide constraint naming convention.

Technical Architecture v2.0 SS10.6 / Data Architecture v2.0 SS2.2: naming
every constraint deterministically is what lets Alembic autogenerate
produce stable, diffable migration files instead of Postgres's default
anonymous constraint names.
"""

from __future__ import annotations

from sqlalchemy import MetaData
from sqlalchemy.orm import DeclarativeBase

NAMING_CONVENTION = {
    "ix": "ix_%(table_name)s_%(column_0_N_name)s",
    "uq": "uq_%(table_name)s_%(column_0_N_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}


class Base(DeclarativeBase):
    metadata = MetaData(naming_convention=NAMING_CONVENTION)
